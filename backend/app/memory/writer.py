"""Memory writer with mandatory provenance (Section 7.2) and corroboration (7.4).

Rules (AGENTS.md / PLAN.md Section 0):
- A lesson may never be written without measurement IDs.  ``write_lesson``
  raises :class:`ProvenanceError` when the list is empty or any ID is unknown.
- Validity is decided by deterministic Python.  Nothing here asks the LLM
  anything; the writer only groups the evidence it is given.
"""

import re
from datetime import datetime, timedelta, timezone
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

from pymongo.database import Database

from backend.app.config import WORKSPACE
from backend.app.embeddings import get_embedding
from backend.app.events import log_event
from backend.app.models import Memory
from backend.app.validity.lattice import (
    evaluate_measurement_member,
    evaluate_memory_member,
    evaluate_support_set,
)

PROVISIONAL_TTL_DAYS = 30

# Prefix used for generated IDs.  Background lessons (B..) are generated by
# the seed loader, not by this writer, so they are not listed here.
_ID_PREFIX = {
    "lesson": "L",
    "failed_attempt": "F",
    "episode": "E",
    "decision_note": "DN",
    "constraint": "C",
    "feedback": "FB",
}


class ProvenanceError(ValueError):
    """Raised when a lesson write has no usable measurement evidence."""


def _dedupe(values: Iterable[str]) -> List[str]:
    return list(dict.fromkeys(values))


def _next_memory_id(db: Database, prefix: str) -> str:
    """Return the next free ``<prefix><integer>`` id for this prefix."""
    pattern = re.compile(rf"^{re.escape(prefix)}(\d+)$")
    highest = 0
    for doc in db.memories.find({}):
        match = pattern.match(str(doc.get("_id", "")))
        if match:
            highest = max(highest, int(match.group(1)))
    return f"{prefix}{highest + 1}"


def group_by_gauge(
    measurement_ids: Sequence[str], measurements: Sequence[Dict[str, Any]]
) -> Tuple[List[List[str]], List[str]]:
    """Group measurement IDs into one support set per instrument.

    Sets are ordered by gauge ID (Section 7.2).  Input order is preserved
    inside a set so the evidence chain reads naturally.
    """
    by_id = {doc["_id"]: doc for doc in measurements}
    ordered_ids = _dedupe(measurement_ids)
    gauges = sorted({by_id[mid]["gauge_id"] for mid in ordered_ids})
    sets = [
        [mid for mid in ordered_ids if by_id[mid]["gauge_id"] == gauge]
        for gauge in gauges
    ]
    return sets, gauges


def write_lesson(
    db: Database,
    *,
    type: str,
    title: str,
    content: str,
    action: str,
    scope: Dict[str, Any],
    measurement_ids: Sequence[str],
    source: Optional[Dict[str, Any]] = None,
    workspace: Optional[str] = None,
    memory_id: Optional[str] = None,
    embedding: Optional[List[float]] = None,
) -> Dict[str, Any]:
    """Write one PROVISIONAL lesson with its evidence grouped by instrument.

    ``embedding`` is only used by the offline fixture path; when omitted the
    text is embedded through the Voyage wrapper (which is disk-cached).
    """
    # 1. Mandatory provenance ------------------------------------------------
    ids = _dedupe([str(mid) for mid in (measurement_ids or [])])
    if not ids:
        raise ProvenanceError("a lesson cannot be written without measurement_ids")

    measurement_docs = list(db.measurements.find({"_id": {"$in": ids}}))
    found = {doc["_id"] for doc in measurement_docs}
    unknown = [mid for mid in ids if mid not in found]
    if unknown:
        raise ProvenanceError(
            "unknown measurement id(s) for lesson evidence: " + ", ".join(unknown)
        )

    # 2. Group by gauge ------------------------------------------------------
    support_sets, gauges = group_by_gauge(ids, measurement_docs)
    derived_from = [mid for subset in support_sets for mid in subset]

    # 3. Embed ---------------------------------------------------------------
    if embedding is None:
        embed_text = f"{title}. {content} Action: {action}"
        embedding = get_embedding(embed_text, input_type="document")
    if len(embedding) != 1024:
        raise ValueError(
            f"embedding must have 1024 dimensions for the memories_vec index, got {len(embedding)}"
        )

    # 4/5. Build and insert --------------------------------------------------
    now = datetime.now(timezone.utc)
    doc: Dict[str, Any] = {
        "_id": memory_id or _next_memory_id(db, _ID_PREFIX.get(type, "L")),
        "workspace": workspace or WORKSPACE,
        "owner": "role:process-engineer",
        "type": type,
        "title": title,
        "content": content,
        "action": action,
        "scope": dict(scope),
        "source": dict(source or {}),
        "support_sets": support_sets,
        "derived_from": derived_from,
        "supports": [],
        "used_by": [],
        "validity_state": "PROVISIONAL",
        "mw_success": 0,
        "mw_fail": 0,
        "embedding": list(embedding),
        "created_at": now,
        "valid_from": now,
        "invalid_at": None,
        "expire_at": now + timedelta(days=PROVISIONAL_TTL_DAYS),
        "version": 1,
        "history": [
            {
                "ts": now,
                "event": "created",
                "from_state": None,
                "to_state": "PROVISIONAL",
                "cause": f"ingest {source.get('ncr_id')}" if source and source.get("ncr_id") else "lesson_writer",
                "event_id": None,
                "note": "Evidence from " + ", ".join(gauges),
            }
        ],
    }

    # Validate against the frozen data contract before touching the database.
    doc = Memory(**doc).model_dump(by_alias=True)
    db.memories.insert_one(doc)

    log_event(
        db,
        "memory_created",
        memory_id=doc["_id"],
        to_state="PROVISIONAL",
        cause=f"ingest {source.get('ncr_id')}" if source and source.get("ncr_id") else "lesson_writer",
        details={"support_sets": support_sets, "type": type},
    )
    return doc


def _upsert_measurement(db: Database, doc: Dict[str, Any]) -> None:
    """Insert/update one measurement, keeping the recorded verdict immutable."""
    record = dict(doc)
    record.setdefault("current_verdict", record.get("verdict", "pass"))
    record.setdefault("verdict_history", [])
    db.measurements.update_one({"_id": record["_id"]}, {"$set": record}, upsert=True)


def set_statuses(
    db: Database,
    support_sets: Sequence[Sequence[str]],
    measurements_map: Optional[Dict[str, Dict[str, Any]]] = None,
) -> List[str]:
    """Evaluate each support set with the Section 6.3 rules (reused, not copied)."""
    measurements_map = measurements_map or {}
    statuses: List[str] = []
    for support_set in support_sets:
        member_statuses: List[str] = []
        for member_id in support_set:
            if member_id.startswith("M") or member_id in measurements_map:
                measurement = measurements_map.get(member_id, {})
                recorded = measurement.get("verdict", "pass")
                current = measurement.get("current_verdict", recorded)
                member_statuses.append(evaluate_measurement_member(recorded, current))
            else:
                memory = db.memories.find_one({"_id": member_id}) or {}
                member_statuses.append(evaluate_memory_member(memory.get("validity_state", "ACTIVE")))
        statuses.append(evaluate_support_set(member_statuses))
    return statuses


def corroborate(
    db: Database,
    memory_id: str,
    *,
    measurement_ids: Sequence[str],
    job_id: str = "",
    measurements: Optional[Sequence[Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    """Add an independent support set and promote the lesson when it holds.

    Section 7.4: new evidence from a gauge that already has a set joins that
    set (the same instrument is not independent); evidence from a new gauge
    creates a new set.  Promotion is allowed here (and only here).
    """
    # 1. Insert and validate the evidence -----------------------------------
    for measurement in measurements or []:
        _upsert_measurement(db, measurement)

    ids = _dedupe([str(mid) for mid in (measurement_ids or [])])
    if not ids:
        raise ProvenanceError("corroboration requires at least one measurement_id")

    measurement_docs = list(db.measurements.find({"_id": {"$in": ids}}))
    by_id = {doc["_id"]: doc for doc in measurement_docs}
    unknown = [mid for mid in ids if mid not in by_id]
    if unknown:
        raise ProvenanceError(
            "unknown measurement id(s) for corroboration: " + ", ".join(unknown)
        )

    memory = db.memories.find_one({"_id": memory_id})
    if memory is None:
        raise KeyError(memory_id)

    old_state = memory.get("validity_state", "PROVISIONAL")
    existing_sets = [list(s) for s in memory.get("support_sets", [])]

    # Which gauge owns each existing set?  A set's first measurement member
    # identifies the instrument.
    set_gauges: Dict[int, str] = {}
    for index, support_set in enumerate(existing_sets):
        for member_id in support_set:
            doc = by_id.get(member_id) or db.measurements.find_one({"_id": member_id})
            if doc is not None:
                set_gauges[index] = doc["gauge_id"]
                break

    new_sets = [list(s) for s in existing_sets]
    added_gauges: List[str] = []
    for gauge in sorted({by_id[mid]["gauge_id"] for mid in ids}):
        gauge_ids = [mid for mid in ids if by_id[mid]["gauge_id"] == gauge]
        target = next(
            (idx for idx, owned_gauge in set_gauges.items() if owned_gauge == gauge),
            None,
        )
        if target is None:
            new_sets.append(gauge_ids)
            set_gauges[len(new_sets) - 1] = gauge
            added_gauges.append(gauge)
        else:
            new_sets[target] = _dedupe(new_sets[target] + gauge_ids)
            added_gauges.append(gauge)

    derived_from = [mid for support_set in new_sets for mid in support_set if str(mid).startswith("M")]

    # 2. Re-evaluate every set (promotion allowed) ---------------------------
    all_member_ids = [mid for support_set in new_sets for mid in support_set]
    all_measurements = {
        doc["_id"]: doc for doc in db.measurements.find({"_id": {"$in": all_member_ids}})
    }
    statuses = set_statuses(db, new_sets, all_measurements)

    # Promotion is allowed here and only here, and it requires independent
    # support: at least two distinct instruments plus a set that still holds.
    # (A second set on the same gauge is not independent evidence; PLAN 7.4.)
    distinct_gauges = sorted({gauge for gauge in set_gauges.values()})
    new_state = "ACTIVE" if ("holds" in statuses and len(distinct_gauges) >= 2) else old_state

    # 3. Write history + state ----------------------------------------------
    now = datetime.now(timezone.utc)
    cause = f"corroborated by {', '.join(sorted(set(added_gauges)))} (job {job_id})"
    note = (
        "Two instruments now support this lesson"
        if len(distinct_gauges) >= 2
        else f"Evidence from {', '.join(sorted(set(added_gauges)))}"
    )
    history_entry = {
        "ts": now,
        "event": "corroborated",
        "from_state": old_state,
        "to_state": new_state,
        "cause": cause,
        "event_id": None,
        "note": note,
    }

    update: Dict[str, Any] = {
        "$set": {
            "support_sets": new_sets,
            "derived_from": _dedupe(derived_from),
            "validity_state": new_state,
        },
        "$inc": {"version": 1},
        "$push": {"history": history_entry},
    }
    if new_state == "ACTIVE":
        update["$unset"] = {"expire_at": ""}
    db.memories.update_one({"_id": memory_id}, update)

    if new_state != old_state:
        log_event(
            db,
            "lesson_state_changed",
            memory_id=memory_id,
            from_state=old_state,
            to_state=new_state,
            cause=cause,
        )

    # 4. Return the updated document ----------------------------------------
    return db.memories.find_one({"_id": memory_id})
